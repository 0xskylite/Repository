// impact kicks (frame offsets into a shot -> seconds): floor pops, hammer landing, the "Unluckily" beat, the final word
export const KICKS: [number, number][] = [
  ...FLOOR_BEATS.map((b, i) => [(L(3) + b * (L(4) - L(3))) / FPS, [0.6, 0.7, 0.9][i]] as [number, number]),
  [A(6, HAMMER_DROP) / FPS, 1.0],
  [A(9, 10) / FPS, 0.5],
  [A(12, 20) / FPS, 0.4],
  [A(16, 60) / FPS, 0.5],
  [(TOTAL - 14) / FPS, 0.7],
];
export const kickAt = (t: number) => {
  let a = 0;
  for (const [t0, g] of KICKS) {
    const n = Math.floor((t - t0) * FPS + 1e-6);
    if (n >= 0 && n < 7) a += g * (n % 2 ? -1 : 1) * (1 - n / 7) ** 1.5;
  }
  return a;
};
export const camAt = (id: number, f: number): Cam => {
  const c = run(CAMS[id], f), a = kickAt(T(f));
  if (!a) return c;
  const d: V3 = [c.look[0] - c.pos[0], c.look[1] - c.pos[1], c.look[2] - c.pos[2]];
  const Ln = Math.hypot(...d), h = Math.hypot(d[0], d[2]) || 1;
  const m = (3 / 640) * Math.tan((c.fov * Math.PI) / 360) * Ln * a;
  return { ...c, look: [c.look[0] - (d[2] / h) * m, c.look[1] + 0.6 * m, c.look[2] + (d[0] / h) * m], roll: c.roll + a * 0.004 };
};
export const keyEnd = (id: number, f: number) => {
  let e = 0;
  for (const k of CAMS[id]) if (f >= k.f) e = k.f + (k.cut ? 0 : k.dur ?? 24);
  return Math.max(f, e);
};


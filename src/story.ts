/** dev check: every camera key and kick must lie inside its own shot (run after retiming) */
export const checkTimeline = (): string[] => {
  const bad: string[] = [];
  for (const [id, keys] of Object.entries(CAMS)) {
    const i = Number(id);
    if (i === 9) continue; // shot 9 shares shot 8's camera keys on purpose
    for (const k of keys) if (k.f < L(i) || k.f >= L(i + 1)) bad.push(`shot ${i}: camera key at ${k.f} outside ${L(i)}-${L(i + 1)}`);
  }
  for (const f of FOREGROUND) { const s = shotAt(f.a); if (f.b > s.b) bad.push(`foreground ${f.kit} ${f.a}-${f.b} leaves shot ${s.id}`); }
  for (let i = 1; i < LINE_F.length; i++) if (LINE_F[i] <= LINE_F[i - 1]) bad.push(`LINE_F not increasing at ${i}`);
  if (HAMMER_DROP >= L(7) - L(6)) bad.push("hammer drop is outside shot 6");
  return bad;
};

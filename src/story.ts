// ---------------- story physics ----------------
export type TowerState = {
  floors: number; // built floors (fractional while a floor pops up)
  tilt: number; // rad toward +x
  sink: number; // how far the low side has sunk into the clay (m)
  firm: number; // 0 soft light clay .. 1 firm dark clay (cut-away colour)
  moss: number; // 0..1 weeds/ivy on the stump during the long pause
  curve: number; // 0..1 banana curve in the upper floors (taller on one side)
  drain: number; // 0..1 water squeezed out of the clay (drops + wet sheen)
};
export const FLOOR_BEATS = [0.14, 0.5, 0.85]; // shot 3: fractions of the shot at which floors 1, 2, 3 pop up
export const BEAT_RISE = 10; // frames for a floor to rise
const floorPop = (id: number, f: number) => {
  const n = L(id + 1) - L(id);
  let fl = 0;
  for (const b of FLOOR_BEATS) fl += easeOut((f - (L(id) + b * n)) / BEAT_RISE);
  return fl;
};
export const towerState = (id: number, f: number): TowerState => {
  const u = clamp01((f - L(id)) / Math.max(1, L(id + 1) - L(id)));
  const T: TowerState = { floors: 0, tilt: 0, sink: 0, firm: 1, moss: 0, curve: 0, drain: 0 };
  switch (id) {
    case 1: case 15: case 17: return { ...T, floors: FLOORS_FINAL, tilt: MODERN_TILT, sink: 0.6 };
    case 16: return { ...T, floors: FLOORS_FINAL, tilt: MODERN_TILT - 0.006 * smooth(u), sink: 0.6 - 0.04 * smooth(u) };
    case 2: return T;
    case 3: return { ...T, floors: floorPop(3, f) };
    case 4: return { ...T, floors: 3, tilt: lerp(0.006, 0.05, smooth(u)), sink: 0.5 * smooth(u), firm: 0 };
    case 5: case 6: case 7: case 8: case 9: return { ...T, floors: 3, tilt: OLD_TILT, sink: 0.55, firm: 0.1 };
    case 12: return { ...T, floors: 3, tilt: OLD_TILT, sink: lerp(0.55, 0.62, smooth(u)), firm: smooth(clamp01((u - 0.15) / 0.7)), drain: Math.sin(Math.PI * clamp01(u * 1.15)) };
    case 13: return { ...T, floors: 3, tilt: OLD_TILT, sink: 0.62, moss: smooth(u) };
    case 14: return { ...T, floors: lerp(3, 7, smooth(clamp01((u - 0.12) / 0.8))), tilt: lerp(OLD_TILT, 0.085, smooth(u)), sink: 0.62, curve: smooth(clamp01((u - 0.12) / 0.8)) };
    default: return T; // 10, 11: the tower is not in the stage
  }
};
